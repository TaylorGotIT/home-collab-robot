def render(issue: tuple) -> str:
    iid, title, phase, labels, est, why, deliverables, dod, deps = issue
    label_str = ", ".join(labels)
    lines = [
        "---",
        f"id: {iid}",
        f"title: {title}",
        f"labels: [{label_str}]",
        f"milestone: {MILESTONES[phase]}",
        f"estimate: {est}",
        f"phase: {phase}",
        f"depends: {deps}",
        "---",
        "",
        f"## 背景",
        "",
        why,
        "",
        "## 交付物",
        "",
    ]
    lines += [f"- [ ] {d}" for d in deliverables]
    lines += ["", "## 验收标准（DoD）", ""]
    lines += [f"- [ ] {d}" for d in dod]
    lines += ["", "## 依赖", "", deps if deps != "无" else "无（可立即开始）", ""]
    lines += [
        "## 备注",
        "",
        f"阶段 {phase}，估算 {est}。相关背景见 [docs/06-开发计划.md](../docs/06-开发计划.md)。",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    OUT.mkdir(exist_ok=True)

    created = skipped = 0
    for issue in ISSUES:
        path = OUT / f"{issue[0]}.md"
        if path.exists() and not args.force:
            skipped += 1
            continue
        path.write_text(render(issue), encoding="utf-8")
        created += 1

    index = [
        "# 任务清单（Issues）",
        "",
        f"共 {len(ISSUES)} 项。导入 GitHub：`python scripts/create_issues.py --dry-run` 先预览，去掉 `--dry-run` 执行。",
        "",
        "| ID | 任务 | 阶段 | 估算 | 依赖 |",
        "| --- | --- | --- | ---: | --- |",
    ]
    for iid, title, phase, _labels, est, _why, _d, _dod, deps in ISSUES:
        index.append(f"| {iid} | {title} | {phase} | {est} | {deps} |")
    index.append("")
    (OUT / "INDEX.md").write_text("\n".join(index), encoding="utf-8")

    print(f"生成 {created} 个，跳过 {skipped} 个（已存在），索引已更新")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
